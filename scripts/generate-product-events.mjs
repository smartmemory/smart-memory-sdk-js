import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';

const BOUNDED_ENUM_FIELDS = [
  ['memory_deleted', 'source'],
  ['search_performed', 'min_score_bucket'],
];

function parseEnumValues(description, eventName, propertyName) {
  if (typeof description !== 'string') {
    throw new Error(`Missing enum description for ${eventName}.${propertyName}`);
  }
  const match = description.match(/^enum:\s*([^—(]+)/u);
  if (!match) {
    throw new Error(`Invalid enum description for ${eventName}.${propertyName}`);
  }
  const values = match[1]
    .split('|')
    .map((value) => value.trim())
    .filter(Boolean);
  if (values.length === 0) {
    throw new Error(`Empty enum description for ${eventName}.${propertyName}`);
  }
  return values;
}

function renderFrozenArray(values) {
  return `Object.freeze([${values.map((value) => JSON.stringify(value)).join(', ')}])`;
}

export function renderProductEvents(contract) {
  if (!contract?.events || typeof contract.events !== 'object' || Array.isArray(contract.events)) {
    throw new Error('Contract must contain an events object');
  }

  const eventNames = Object.keys(contract.events).sort();
  const propertyLines = eventNames.map((eventName) => {
    const event = contract.events[eventName];
    if (!event || typeof event !== 'object' || Array.isArray(event)) {
      throw new Error(`Event ${eventName} must be an object`);
    }
    const propertyNames = Object.keys(event).sort();
    return `  ${JSON.stringify(eventName)}: ${renderFrozenArray(propertyNames)},`;
  });

  const enums = {};
  for (const [eventName, propertyName] of BOUNDED_ENUM_FIELDS) {
    const description = contract.events[eventName]?.[propertyName];
    if (description === undefined) {
      continue;
    }
    enums[eventName] ??= {};
    enums[eventName][propertyName] = parseEnumValues(
      description,
      eventName,
      propertyName,
    );
  }

  const enumLines = [];
  for (const eventName of Object.keys(enums).sort()) {
    enumLines.push(`  ${JSON.stringify(eventName)}: Object.freeze({`);
    for (const propertyName of Object.keys(enums[eventName]).sort()) {
      enumLines.push(
        `    ${JSON.stringify(propertyName)}: ${renderFrozenArray(enums[eventName][propertyName])},`,
      );
    }
    enumLines.push('  }),');
  }

  return [
    '// Generated by scripts/generate-product-events.mjs.',
    '// Do not edit by hand.',
    '',
    'export const PRODUCT_EVENT_PROPERTIES = Object.freeze({',
    ...propertyLines,
    '});',
    '',
    'export const PRODUCT_EVENT_ENUM_VALUES = Object.freeze({',
    ...enumLines,
    '});',
    '',
  ].join('\n');
}

function defaultOutputPath() {
  return fileURLToPath(
    new URL('../src/react/analytics/productEvents.generated.js', import.meta.url),
  );
}

export async function generateProductEvents({ contractPath, outputPath, check = false }) {
  if (!contractPath) {
    throw new Error('Missing required --contract <path>');
  }
  const targetPath = outputPath || defaultOutputPath();
  const contract = JSON.parse(await readFile(contractPath, 'utf8'));
  const generated = renderProductEvents(contract);

  if (check) {
    let current;
    try {
      current = await readFile(targetPath, 'utf8');
    } catch {
      throw new Error(`${targetPath} is out of date`);
    }
    if (current !== generated) {
      throw new Error(`${targetPath} is out of date`);
    }
    return true;
  }

  await writeFile(targetPath, generated, 'utf8');
  return true;
}

function parseArguments(argv) {
  const options = { check: false };
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === '--check') {
      options.check = true;
      continue;
    }
    if (argument === '--contract') {
      options.contractPath = argv[index + 1];
      index += 1;
      continue;
    }
    throw new Error(`Unknown argument: ${argument}`);
  }
  return options;
}

const isCommandLine = process.argv[1]
  && pathToFileURL(process.argv[1]).href === import.meta.url;

if (isCommandLine) {
  try {
    const options = parseArguments(process.argv.slice(2));
    await generateProductEvents(options);
    process.stdout.write(options.check
      ? 'Product event allowlist is up to date.\n'
      : 'Product event allowlist generated.\n');
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  }
}
